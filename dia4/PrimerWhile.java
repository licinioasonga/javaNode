package dia4;


public class PrimerWhile {
        public static void main(String[] args) {
        
        int numero = 1;
       
        while (numero <= 5) {
            
            System.out.println("Vuelta número: " + numero);
            
            numero++;
           
        }
        
        System.out.println("El bucle ha terminado.");
     
    }

}