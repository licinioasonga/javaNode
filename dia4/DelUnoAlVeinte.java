package dia4;

public class DelUnoAlVeinte {
    public static void main(String[] args) {
        
        int numero = 1;
       
        while (numero <= 20) {
            
            System.out.println("Número: " + numero);
            
        numero++;
           
        }
        
        System.out.println("El bucle ha terminado.");
     
    }
    
}
