package dia1;

public class TiposDistintos {public static void main(String[] args) {
    
        // Declaramos una variable de tipo String
        String nombre = "Licinio";

        // Declaramos una variable de tipo int
        int edad = 46;

        // Declaramos una variable de tipo double
        double altura = 1.75;

        // Declaramos una variable de tipo boolean
        boolean esEstudiante = true;

        // Imprimimos los valores de las variables en la consola
        System.out.println("Nombre: " + nombre);
        System.out.println("Edad: " + edad);
        System.out.println("Altura: " + altura);
        System.out.println("Es estudiante: " + esEstudiante);
    }
}
    

