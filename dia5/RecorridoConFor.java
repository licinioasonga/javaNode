package dia5;

public class RecorridoConFor {
    
    public static void main(String[] args) {
        
        int[] notas = { 6, 8, 5, 9, 7 };
       
        for (int i = 0; i < notas.length; i++) {
           
            System.out.println("Posición " + i + ": " + notas[i]);
            
        }
        
    }
   
}